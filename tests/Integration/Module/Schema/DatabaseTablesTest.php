<?php

declare(strict_types=1);

namespace App\Tests\Integration\Module\Schema;

use App\Module\Metadata\Contract\Dto\KeyType;
use App\Module\Metadata\Contract\MetadataManagerInterface;
use App\Module\Schema\Application\Table\ProposedNames;
use App\Module\Schema\Contract\DatabaseTablesInterface;
use App\Module\Schema\Contract\Dto\DatabaseTable;
use App\Module\Schema\Contract\Dto\TableKind;
use App\Shared\Message\Message;
use Doctrine\DBAL\Connection;
use PHPUnit\Framework\Attributes\DataProvider;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

/**
 * The tables loaded into the data schema by hand, read from the catalog: which ones no object
 * owns, what they hold, and what keeps one from becoming an object. The tables are made by SQL
 * in the test's transaction, as a dump would make them.
 */
final class DatabaseTablesTest extends KernelTestCase
{
    public function testListsOnlyTheTablesNoObjectOwns(): void
    {
        $manager = self::getContainer()->get(MetadataManagerInterface::class);
        $manager->createObject('tag', 'Tag', 'Tags');
        $manager->createObject('contact', 'Contact', 'Contacts');
        $manager->createField('contact', 'tags', 'many_to_many', 'Tags', settings: ['target' => 'tag']);
        $manager->createObject('old', 'Old', 'Olds');
        $manager->archiveObject('old');
        $this->sql('CREATE TABLE data.project (id serial PRIMARY KEY, title text NOT NULL)');
        // Not the workspace's data schema: never listed.
        $this->sql('CREATE TABLE public.elsewhere (id serial PRIMARY KEY)');

        self::assertSame(['project'], array_map(static fn (DatabaseTable $table): string => $table->name, $this->tables()->unmanaged()));
        self::assertNull($this->tables()->find('c_contact'));
        self::assertNull($this->tables()->find('l_contact__tags'));
        self::assertNull($this->tables()->find('c_old'));
        self::assertNull($this->tables()->find('elsewhere'));
    }

    public function testDescribesATable(): void
    {
        $this->sql('CREATE TABLE data."ProjectTask" (
            task_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code varchar(20) NOT NULL UNIQUE,
            title text,
            seats integer DEFAULT 0,
            starts_on date,
            UNIQUE (title, starts_on)
        )');
        $this->sql('CREATE TABLE data.project_task_item (id uuid PRIMARY KEY, task bigint REFERENCES data."ProjectTask" (task_id) ON DELETE CASCADE)');
        $this->sql('INSERT INTO data."ProjectTask" (code) VALUES (\'A\'), (\'B\')');
        $this->sql('ANALYZE data."ProjectTask"');

        $task = $this->table('ProjectTask');
        self::assertSame(TableKind::Table, $task->kind);
        self::assertSame(['task_id'], $task->primaryKey);
        self::assertSame(KeyType::Integer, $task->keyType);
        self::assertSame('project_task', $task->proposedName);
        self::assertSame(2, $task->rows);
        self::assertSame(['task_id', 'code', 'title', 'seats', 'starts_on'], array_map(static fn ($column): string => $column->name, $task->columns));
        self::assertSame('character varying(20)', $task->column('code')?->type);
        self::assertFalse($task->column('code')->nullable);
        self::assertTrue($task->column('task_id')?->identity);
        self::assertSame('0', $task->column('seats')?->default);
        self::assertEqualsCanonicalizing([['code'], ['title', 'starts_on']], $task->uniques);
        self::assertTrue($task->isAdoptable());

        $item = $this->table('project_task_item');
        self::assertSame(KeyType::Uuid, $item->keyType);
        self::assertCount(1, $item->foreignKeys);
        $key = $item->foreignKeys[0];
        self::assertSame([['task'], 'data', 'ProjectTask', ['task_id'], 'CASCADE'], [$key->columns, $key->referencedSchema, $key->referencedTable, $key->referencedColumns, $key->onDelete]);
    }

    public function testTellsWhyATableCannotBecomeAnObject(): void
    {
        $this->sql('CREATE TABLE data.loose (name text)');
        $this->sql('CREATE TABLE data.pairs (a int, b int, PRIMARY KEY (a, b))');
        $this->sql('CREATE TABLE data.codes (code text PRIMARY KEY)');
        $this->sql('CREATE TABLE data.watched (id int PRIMARY KEY)');
        $this->sql('CREATE FUNCTION data.noop() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$');
        $this->sql('CREATE TRIGGER audit BEFORE INSERT ON data.watched FOR EACH ROW EXECUTE FUNCTION data.noop()');
        $this->sql('CREATE TABLE data.read (id int PRIMARY KEY)');
        $this->sql('CREATE VIEW data.read_all AS SELECT id FROM data.read');

        self::assertSame(['It has no primary key: give it one first.'], $this->refusals('loose'));
        self::assertSame(['Its primary key has several columns (a, b): such a table cannot become an object yet.'], $this->refusals('pairs'));
        self::assertSame(['Its primary key is of type text: only a UUID or an integer can be the key of an object.'], $this->refusals('codes'));
        self::assertSame(['Trigger audit acts on it, and would break: drop it first.'], $this->refusals('watched'));
        self::assertSame(['View data.read_all reads it, and would break: drop it first.'], $this->refusals('read'));
        self::assertSame(TableKind::View, $this->table('read_all')->kind);
        self::assertSame(['It is a view: only a table can become an object.'], $this->refusals('read_all'));
    }

    public function testProposesNoNameAnObjectHasAlready(): void
    {
        self::getContainer()->get(MetadataManagerInterface::class)->createObject('ticket', 'Ticket', 'Tickets');
        $this->sql('CREATE TABLE data.tickets (id int PRIMARY KEY)');
        $this->sql('CREATE TABLE data.ticket_copy (id int PRIMARY KEY)');
        // A table named as an object's would be, but no object owns it: a leftover.
        $this->sql('CREATE TABLE data.c_invoice (id int PRIMARY KEY)');

        self::assertSame('tickets', $this->table('tickets')->proposedName);
        self::assertSame('invoice', $this->table('c_invoice')->proposedName);
        $this->sql('ALTER TABLE data.ticket_copy RENAME TO "Ticket"');
        self::assertNull($this->table('Ticket')->proposedName);
        self::assertTrue($this->table('Ticket')->isAdoptable());
    }

    #[DataProvider('names')]
    public function testMakesMachineNamesOfTableNames(string $table, ?string $expected): void
    {
        self::assertSame($expected, ProposedNames::forTable($table));
    }

    /**
     * @return iterable<string, array{string, string|null}>
     */
    public static function names(): iterable
    {
        yield 'already one' => ['project_task', 'project_task'];
        yield 'camel case' => ['ProjectTaskItem', 'project_task_item'];
        yield 'dashes and spaces' => ['project-task item', 'project_task_item'];
        yield 'double underscores' => ['project__task', 'project_task'];
        yield 'a digit first' => ['2024_sales', 't_2024_sales'];
        yield 'the object prefix' => ['c_invoice', 'invoice'];
        yield 'too long' => [str_repeat('a', 60), str_repeat('a', 50)];
        yield 'nothing left' => ['__', null];
        yield 'one letter' => ['x', null];
    }

    private function table(string $name): DatabaseTable
    {
        return $this->tables()->find($name) ?? self::fail(\sprintf('No unmanaged table "%s".', $name));
    }

    /**
     * @return list<string>
     */
    private function refusals(string $table): array
    {
        return array_map(static fn (Message $reason): string => (string) $reason, $this->table($table)->refusals);
    }

    private function tables(): DatabaseTablesInterface
    {
        return self::getContainer()->get(DatabaseTablesInterface::class);
    }

    private function sql(string $sql): void
    {
        self::getContainer()->get(Connection::class)->executeStatement($sql);
    }
}
